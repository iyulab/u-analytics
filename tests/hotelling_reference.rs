#[test]
fn phase_i_matches_numpy_and_scipy() {
    for c in cases() {
        let data = rows(c.data, c.p);
        assert_eq!(data.len(), c.m, "{}", c.name);
        for (k, &alpha) in ALPHAS.iter().enumerate() {
            let chart = phase_i(&data, alpha).expect("a chart");
            let what = |s: &str| format!("{} {s} (alpha {alpha})", c.name);
            // The estimates are the sample mean and covariance (ddof = 1).
            for (j, &want) in c.mean.iter().enumerate() {
                close(chart.estimates.mean[j], want, 1e-12, &what("mean"));
            }
            for (i, row) in chart.estimates.covariance.iter().enumerate() {
                for (j, &got) in row.iter().enumerate() {
                    close(got, c.cov[i * c.p + j], 1e-10, &what("covariance"));
                }
            }
            for (i, &want) in c.t2.iter().enumerate() {
                close(chart.t2[i], want, 1e-8, &what(&format!("T² of row {i}")));
            }
            close(chart.ucl, c.phase_i_ucl[k], 1e-9, &what("Phase I limit"));
        }
    }
}

#[test]
fn phase_ii_matches_numpy_and_scipy() {
    for c in cases() {
        let estimates = HotellingEstimates {
            mean: c.mean.to_vec(),
            covariance: c
                .cov
                .chunks(c.p)
                .map(<[f64]>::to_vec)
                .collect::<Vec<Vec<f64>>>(),
            m: c.m,
        };
        let new = rows(c.new, c.p);
        for (k, &alpha) in ALPHAS.iter().enumerate() {
            let chart = phase_ii(&new, &estimates, alpha).expect("a chart");
            let what = |s: &str| format!("{} {s} (alpha {alpha})", c.name);
            for (i, &want) in c.new_t2.iter().enumerate() {
                close(
                    chart.t2[i],
                    want,
                    1e-8,
                    &what(&format!("T² of new row {i}")),
                );
            }
            close(chart.ucl, c.phase_ii_ucl[k], 1e-9, &what("Phase II limit"));
        }
    }
}
