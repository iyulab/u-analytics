fn subgroups_of(flat: &[f64], n: usize, p: usize) -> Vec<Vec<Vec<f64>>> {
    flat.chunks(n * p).map(|g| rows(g, p)).collect()
}

#[test]
fn subgroup_phase_i_matches_numpy_and_scipy() {
    for c in sub_cases() {
        let data = subgroups_of(c.data, c.n, c.p);
        assert_eq!(data.len(), c.m, "{}", c.name);
        for (k, &alpha) in ALPHAS.iter().enumerate() {
            let chart = subgroup_phase_i(&data, alpha).expect("a chart");
            let what = |s: &str| format!("{} {s} (alpha {alpha})", c.name);
            for (j, &want) in c.mean.iter().enumerate() {
                close(chart.estimates.mean[j], want, 1e-12, &what("grand mean"));
            }
            for (i, row) in chart.estimates.covariance.iter().enumerate() {
                for (j, &got) in row.iter().enumerate() {
                    close(got, c.cov[i * c.p + j], 1e-10, &what("pooled covariance"));
                }
            }
            for (i, &want) in c.t2.iter().enumerate() {
                close(
                    chart.t2[i],
                    want,
                    1e-8,
                    &what(&format!("T² of subgroup {i}")),
                );
            }
            close(chart.ucl, c.phase_i_ucl[k], 1e-9, &what("Phase I limit"));
        }
    }
}

