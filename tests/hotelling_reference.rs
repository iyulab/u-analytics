fn close(got: f64, want: f64, rel: f64, what: &str) {
    assert!(
        (got - want).abs() <= rel * want.abs().max(1e-300),
        "{what}: got {got}, reference {want} (relative {:e})",
        ((got - want) / want).abs()
    );
}

