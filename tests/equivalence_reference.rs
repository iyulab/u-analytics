fn run(c: &Case) -> Option<EquivalenceResult> {
    let (low, high) = c.margins;
    match c.kind {
        Kind::One => tost_one_sample(c.a, c.target, low, high, c.alpha),
        Kind::Paired => tost_paired(c.a, c.b, low, high, c.alpha),
        Kind::Two => tost_two_sample(c.a, c.b, low, high, c.alpha, c.equal_variance),
    }
}

fn close(got: f64, want: f64, tolerance: f64, what: &str, case: usize) {
    let scale = want.abs().max(1e-300);
    assert!(
        ((got - want) / scale).abs() <= tolerance,
        "case {case} {what}: got {got:e}, want {want:e}"
    );
}

#[test]
fn matches_statsmodels() {
    for (i, c) in CASES.iter().enumerate() {
        let r = run(c).expect("a valid case");
        let w = &c.want;
        close(r.estimate, w.estimate, 1e-12, "estimate", i);
        close(r.std_error, w.std_error, 1e-12, "std_error", i);
        close(r.df, w.df, 1e-12, "df", i);
        close(r.t_lower, w.t_lower, 1e-11, "t_lower", i);
        close(r.t_upper, w.t_upper, 1e-11, "t_upper", i);
        // a p-value is compared in relative terms down to the last tail digits
        close(r.p_lower, w.p_lower, 1e-9, "p_lower", i);
        close(r.p_upper, w.p_upper, 1e-9, "p_upper", i);
        close(r.p_value, w.p_value, 1e-9, "p_value", i);
        close(r.ci_lower, w.ci.0, 1e-11, "ci_lower", i);
        close(r.ci_upper, w.ci.1, 1e-11, "ci_upper", i);
    }
}

/// The p-value of the procedure is the larger of the two, and equivalence at α
/// is the same statement as the 1 − 2α interval lying inside the margins.
#[test]
fn the_three_statements_of_equivalence_agree() {
    for (i, c) in CASES.iter().enumerate() {
        let r = run(c).unwrap();
        // the interval is of the difference, so the margins are on the same scale
        let (low, high) = c.margins;
        assert_eq!(r.p_value, r.p_lower.max(r.p_upper), "case {i}");
        let inside = r.ci_lower > low && r.ci_upper < high;
        assert_eq!(r.equivalent, r.p_value < c.alpha, "case {i}");
        assert_eq!(r.equivalent, inside, "case {i}: p = {:e}", r.p_value);
    }
}

/// Swapping the samples and negating the margins is the same test.
#[test]
fn swapping_the_samples_mirrors_the_test() {
    for c in CASES
        .iter()
        .filter(|c| matches!(c.kind, Kind::Two | Kind::Paired))
    {
        let (low, high) = c.margins;
        let r = run(c).unwrap();
        let m = match c.kind {
            Kind::Two => tost_two_sample(c.b, c.a, -high, -low, c.alpha, c.equal_variance),
            _ => tost_paired(c.b, c.a, -high, -low, c.alpha),
        }
        .unwrap();
        assert_eq!(m.estimate, -r.estimate);
        assert!((m.p_value - r.p_value).abs() <= 1e-12 * r.p_value.max(1e-300));
        assert_eq!(m.equivalent, r.equivalent);
        assert!((m.ci_lower + r.ci_upper).abs() <= 1e-12 * r.ci_upper.abs().max(1.0));
    }
}

#[test]
fn refuses_what_it_cannot_answer() {
    let a = [1.0, 2.0, 3.0, 4.0];
    let b = [1.5, 2.5, 3.5, 4.5];
    assert!(tost_one_sample(&a, 2.0, -1.0, 1.0, 0.05).is_some());
    // margins: reversed, equal, not finite
    assert!(tost_one_sample(&a, 2.0, 1.0, -1.0, 0.05).is_none());
    assert!(tost_one_sample(&a, 2.0, 1.0, 1.0, 0.05).is_none());
    assert!(tost_one_sample(&a, 2.0, f64::NEG_INFINITY, 1.0, 0.05).is_none());
    assert!(tost_one_sample(&a, f64::NAN, -1.0, 1.0, 0.05).is_none());
    // level: α must leave a 1 − 2α interval
    for alpha in [0.0, 0.5, 0.7, -0.1, f64::NAN, 1.0] {
        assert!(
            tost_one_sample(&a, 2.0, -1.0, 1.0, alpha).is_none(),
            "{alpha}"
        );
    }
    // data
    assert!(tost_one_sample(&a[..1], 2.0, -1.0, 1.0, 0.05).is_none());
    assert!(tost_one_sample(&[3.0, 3.0, 3.0], 2.0, -1.0, 1.0, 0.05).is_none());
    assert!(tost_one_sample(&[1.0, f64::NAN, 3.0], 2.0, -1.0, 1.0, 0.05).is_none());
    assert!(tost_paired(&a, &b[..3], -1.0, 1.0, 0.05).is_none());
    assert!(tost_two_sample(&a, &b[..1], -1.0, 1.0, 0.05, false).is_none());
    assert!(tost_two_sample(&[1.0, 1.0], &[2.0, 2.0], -1.0, 1.0, 0.05, false).is_none());
}

#[test]
fn a_clearly_equivalent_and_a_clearly_different_process() {
    let tight = [10.01, 9.99, 10.0, 10.02, 9.98, 10.0, 10.01, 9.99];
    let r = tost_one_sample(&tight, 10.0, -0.1, 0.1, 0.05).unwrap();
    assert!(r.equivalent && r.p_value < 1e-6);
    // the same sample against margins it does not fit
    let r = tost_one_sample(&tight, 10.0, 0.5, 1.0, 0.05).unwrap();
    assert!(!r.equivalent && r.p_value > 0.99);
}
