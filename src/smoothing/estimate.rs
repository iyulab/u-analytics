//! Estimation of smoothing constants by least squares.
//!
//! The constants left unset are those minimising the sum of squared one-step
//! errors over the observations the smoother updates on (Hyndman et al. 2008,
//! §5.1 — the least-squares estimate, as statsmodels' `ExponentialSmoothing.fit`
//! computes by default). Each free constant is searched on the logistic scale,
//! so it stays strictly inside (0, 1): a 5-point grid per constant gives the
//! start, then the Nelder–Mead simplex method refines it. The search is
//! deterministic.

use u_numflow::optimize::{nelder_mead, NelderMeadOptions};

/// A logistic-scale value far enough out that the constant is 2e-9 from the
/// end of (0, 1) without reaching it.
const EDGE: f64 = 20.0;

fn constant(u: f64) -> f64 {
    1.0 / (1.0 + (-u.clamp(-EDGE, EDGE)).exp())
}

fn logit(p: f64) -> f64 {
    (p / (1.0 - p)).ln()
}

/// The constants `fixed` with every `None` replaced by the value that
/// minimises `sse`; `sse` is called with all of them.
pub(crate) fn least_squares(fixed: &[Option<f64>], sse: impl Fn(&[f64]) -> f64) -> Vec<f64> {
    let free: Vec<usize> = (0..fixed.len()).filter(|&i| fixed[i].is_none()).collect();
    let full = |u: &[f64]| -> Vec<f64> {
        let mut c: Vec<f64> = fixed.iter().map(|v| v.unwrap_or(0.0)).collect();
        for (k, &i) in free.iter().enumerate() {
            c[i] = constant(u[k]);
        }
        c
    };
    if free.is_empty() {
        return full(&[]);
    }
    let grid: Vec<f64> = [0.1, 0.3, 0.5, 0.7, 0.9]
        .iter()
        .map(|&p| logit(p))
        .collect();
    let d = free.len();
    let mut start = vec![grid[0]; d];
    let mut best = f64::INFINITY;
    let mut point = vec![0usize; d];
    loop {
        let u: Vec<f64> = point.iter().map(|&g| grid[g]).collect();
        let v = sse(&full(&u));
        if v < best {
            best = v;
            start = u;
        }
        // Next grid point, odometer order.
        let mut k = 0;
        while k < d {
            point[k] += 1;
            if point[k] < grid.len() {
                break;
            }
            point[k] = 0;
            k += 1;
        }
        if k == d {
            break;
        }
    }
    let m = nelder_mead(
        |u| sse(&full(u)),
        &start,
        NelderMeadOptions::for_dimension(d),
    );
    if m.value <= best {
        full(&m.x)
    } else {
        full(&start)
    }
}

/// The sum of squared one-step errors `data[t] − fitted[t]` for `t >= first`.
pub(crate) fn one_step_sse(data: &[f64], fitted: &[f64], first: usize) -> f64 {
    data.iter()
        .zip(fitted)
        .skip(first)
        .map(|(x, f)| (x - f).powi(2))
        .sum()
}

/// The least-squares constants against statsmodels 0.15.0 with the same
/// initial states, on seeded series rounded to 3 places: a noisy level
/// (simple) and a noisy line (Holt) against `ExponentialSmoothing(...,
/// initialization_method="known").fit()`; a period-6 seasonal line (additive
/// Holt-Winters) against `ETSModel(..., error="add").fit()` -- whose Gaussian
/// likelihood peaks where the sum of squares is least -- with its state-space
/// constants converted (beta = beta*/alpha, gamma = gamma*/(1 - alpha)), since
/// `ExponentialSmoothing` updates the season on y - l(t-1) - b(t-1), not on
/// Winters' y - l(t) as here.
