    /// The least-squares constants reach the reference's sum of squares (or
    /// below it), and at the reference's own constants the smoother gives the
    /// same sum -- the same model, the same objective.
    fn check(sse_at: impl Fn(&[f64]) -> f64, ours: &[f64], params: &[f64], sse: f64) {
        let at_reference = sse_at(params);
        assert!(
            (at_reference - sse).abs() <= 1e-9 * sse,
            "objective differs from the reference's: {at_reference} vs {sse}"
        );
        let at_ours = sse_at(ours);
        assert!(
            at_ours <= sse * (1.0 + 1e-6),
            "{ours:?}: {at_ours} vs {params:?}: {sse}"
        );
        for (a, b) in ours.iter().zip(params) {
            assert!((a - b).abs() < 1e-3, "{ours:?} vs {params:?}");
        }
    }

    #[test]
    fn ses_least_squares_matches_statsmodels() {
        let s = SimpleExponentialSmoothing::fit(SES_DATA).unwrap();
        let sse = |c: &[f64]| {
            let r = SimpleExponentialSmoothing::new(c[0])
                .unwrap()
                .smooth(SES_DATA)
                .unwrap();
            one_step_sse(SES_DATA, &r.fitted, SesResult::FIRST_ERROR)
        };
        check(sse, &[s.alpha()], SES_PARAMS, SES_SSE);
    }

    #[test]
    fn holt_least_squares_matches_statsmodels() {
        let h = HoltLinear::fit(HOLT_DATA, None, None).unwrap();
        let sse = |c: &[f64]| {
            let r = HoltLinear::new(c[0], c[1])
                .unwrap()
                .smooth(HOLT_DATA)
                .unwrap();
            one_step_sse(HOLT_DATA, &r.fitted, HoltResult::FIRST_ERROR)
        };
        check(sse, &[h.alpha(), h.beta()], HOLT_PARAMS, HOLT_SSE);
    }

    #[test]
    fn holt_winters_least_squares_matches_statsmodels() {
        let w = HoltWinters::fit(HW_DATA, None, None, None, 6, Seasonality::Additive).unwrap();
        let sse = |c: &[f64]| {
            let r = HoltWinters::new(c[0], c[1], c[2], 6, Seasonality::Additive)
                .unwrap()
                .smooth(HW_DATA)
                .unwrap();
            one_step_sse(HW_DATA, &r.fitted, 6)
        };
        let r = w.smooth(HW_DATA).unwrap();
        check(sse, &[r.alpha, r.beta, r.gamma], HW_PARAMS, HW_SSE);
    }

    #[test]
    fn a_given_constant_is_held() {
        let h = HoltLinear::fit(HOLT_DATA, Some(0.3), None).unwrap();
        assert_eq!(h.alpha(), 0.3);
        let free = HoltLinear::fit(HOLT_DATA, None, None).unwrap();
        assert_ne!(h.beta(), free.beta());
    }
